const fs = require('node:fs');
const path = require('node:path');
const jestPackage = require('jest/package.json');

const MEASUREMENTS_PATH = path.resolve('test-results/measurements.jsonl');
const DEFAULT_REPORT = 'docs/test-reports/automated-test-results.md';

const BLOCKED_PREFIX = 'BLOCKED:';

const STATUS = { passed: 'PASS', failed: 'FAIL', pending: 'SKIPPED', todo: 'SKIPPED' };

function readMeasurements() {
  if (!fs.existsSync(MEASUREMENTS_PATH)) {
    return [];
  }

  return fs.readFileSync(MEASUREMENTS_PATH, 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((line) => JSON.parse(line));
}

function firstLine(message) {
  return message.replace(/\u001b\[[0-9;]*m/g, '').trim().split('\n')[0];
}

class MarkdownReporter {
  onRunStart() {
    fs.rmSync(MEASUREMENTS_PATH, { force: true });
  }

  onRunComplete(_contexts, results) {
    const reportPath = path.resolve(process.env.BRIDGE_REPORT_PATH || DEFAULT_REPORT);
    const host = process.env.BRIDGE_HOST || '192.168.1.200';
    const port = process.env.BRIDGE_PORT || '4001';
    const rows = [];
    const failures = [];

    for (const file of results.testResults) {
      if (file.testExecError) {
        failures.push(`${path.basename(file.testFilePath)}: ${firstLine(file.testExecError.message)}`);
      }

      for (const test of file.testResults) {
        const seconds = test.duration == null ? '-' : (test.duration / 1000).toFixed(2);

        rows.push(`| ${test.title} | ${STATUS[test.status] || test.status} | ${seconds} |`);

        for (const message of test.failureMessages) {
          failures.push(`${test.title}: ${firstLine(message)}`);
        }
      }
    }

    rows.sort();

    const failed = results.numFailedTests + results.numFailedTestSuites + results.numRuntimeErrorTestSuites > 0;
    const blocked = failed && failures.every((failure) => failure.includes(BLOCKED_PREFIX));
    const overall = blocked ? 'BLOCKED: no test could run' : failed ? 'FAIL' : 'PASS';
    const measurements = readMeasurements();

    const lines = [
      '# Automated Integration Test Results',
      '',
      'This file is generated by Jest. It reports automated tests only, and it does not replace the records in `docs/test-records/`.',
      '',
      '| Field | Value |',
      '|---|---|',
      '| Validation type | **Automated, over TCP** |',
      `| Overall result | **${overall}** |`,
      `| Run finished | ${new Date().toISOString()} |`,
      `| Target | \`${host}:${port}\` |`,
      `| Firmware | ${process.env.BRIDGE_FIRMWARE ? `\`${process.env.BRIDGE_FIRMWARE}\`` : 'Not provided (set `BRIDGE_FIRMWARE`)'} |`,
      `| Node.js | ${process.version} |`,
      `| Jest | ${jestPackage.version} |`,
      `| Tests | ${results.numPassedTests} passed, ${results.numFailedTests} failed, ${results.numPendingTests} skipped |`,
      '',
      '## Results',
      '',
      '| Test | Result | Seconds |',
      '|---|---|---|',
      ...rows,
    ];

    if (measurements.length > 0) {
      lines.push('', '## Measurements', '', '| Test | Measurement | Value |', '|---|---|---|');

      for (const { test, name, value } of measurements) {
        lines.push(`| ${test} | ${name} | \`${value}\` |`);
      }
    }

    if (failures.length > 0) {
      lines.push('', blocked ? '## Why the Run Was Blocked' : '## Failures', '');

      if (blocked) {
        lines.push('This is not a firmware result. The tests stopped before exercising the bridge.', '');
      }

      for (const failure of [...new Set(failures.map((text) => (blocked ? text.slice(text.indexOf(BLOCKED_PREFIX)) : text)))]) {
        lines.push(`- ${failure}`);
      }
    }

    lines.push(
      '',
      '## What This Report Does Not Cover',
      '',
      '- **H7 and H8 are manual.** They need a physical cable disconnection, so they are never part of this report. See `manual-test-procedures.md`.',
      '- **H6 is opt-in.** It appears as skipped unless it was run with `npm run test:h6`.',
      '- **The firmware is not read from the device.** The `Firmware` field is what the operator declared.',
      '- **Echo tests need the GPIO32 to GPIO33 jumper.** They exercise FR-3 and FR-4 together, and cannot observe the UART pins directly.',
      '- **Serial logs are not captured.** Close reasons such as `client stalled` must be confirmed in the ESP32 monitor.',
      '',
    );

    fs.mkdirSync(path.dirname(reportPath), { recursive: true });
    fs.writeFileSync(reportPath, lines.join('\n'));
    process.stdout.write(`\nReport written to ${path.relative(process.cwd(), reportPath)}\n`);
  }
}

module.exports = MarkdownReporter;
